// Mengambil bahasa aktif ('id' atau 'en') dari preferensi tersimpan
function dvGetLang() {
  try {
    const p = dvGetPreferences();
    return p && p.bahasa === 'en' ? 'en' : 'id';
  } catch (e) {
    return 'id';
  }
}

// Terjemahan satu key secara manual (dipakai di JS, misal saat generate
// konten dinamis seperti toast, empty state, dst). Placeholder {nama}
// dkk bisa diisi lewat parameter kedua (object).
function dvT(key, vars) {
  const lang = dvGetLang();
  let text = (DV_I18N[lang] && DV_I18N[lang][key]) || (DV_I18N.id && DV_I18N.id[key]) || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return text;
}

// Menerapkan bahasa ke seluruh elemen berlabel data-i18n* di halaman
// yang sedang aktif. Dipanggil otomatis oleh settings.js setiap
// halaman dimuat & setiap preferensi bahasa berubah.
function dvApplyLanguage() {
  const lang = dvGetLang();
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (DV_I18N[lang] && DV_I18N[lang][key] !== undefined) {
      el.textContent = DV_I18N[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (DV_I18N[lang] && DV_I18N[lang][key] !== undefined) {
      el.setAttribute('placeholder', DV_I18N[lang][key]);
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (DV_I18N[lang] && DV_I18N[lang][key] !== undefined) {
      el.setAttribute('title', DV_I18N[lang][key]);
    }
  });

  // Sudah selesai diterjemahkan — ungkap halaman (lihat CSS
  // html[data-lang-loading] body{opacity:0} di dashboard.css, dan
  // <script> sinkron di <head> tiap halaman yang men-set atribut ini).
  document.documentElement.removeAttribute('data-lang-loading');
}